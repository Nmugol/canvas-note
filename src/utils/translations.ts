export type TranslationKeys = keyof typeof translations.pl;

export function useTranslation() {
	const intl = useIntl();
	const { settings } = useSettings();
	const lang = settings.language || "pl";

	const t = (key: TranslationKeys, values?: Record<string, any>): string => {
		return intl.formatMessage({ id: key, defaultMessage: translations.pl[key] }, values);
	};

	return { t, lang };
}
